// Extracts locales from the pinned UMD bundle and creates separate npm package entry points. Runs
// separately from the build and checks that the source data is reproducible.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { createContext, runInContext } from 'node:vm';

const { values } = parseArgs({
  options: { artifacts: { type: 'string', default: '.upstream/artifacts' } }
});
const artifacts = resolve(values.artifacts);
const registry = JSON.parse(readFileSync('docs/reference/ant-design-porting/registry.json', 'utf8'));
const { version, revision, archiveSha256 } = registry.upstream;
const source = 'package/dist/antd-with-locales.min.js';

/** Fingerprint of an archive or JSON dictionary for checking dist. */
function checksum(input) {
  return createHash('sha256').update(input).digest('hex');
}

/** Verifies the release and loads the UMD bundle with its pinned runtimes. */
function readScripts() {
  const archive = join(artifacts, `antd-${version}.tgz`);
  if (checksum(readFileSync(archive)) !== archiveSha256) {
    throw new Error(`Unexpected archive contents for Ant Design ${version}`);
  }

  const runtimes = [
    join(artifacts, 'react-18.3.1/umd/react.production.min.js'),
    join(artifacts, 'react-dom-18.3.1/umd/react-dom.production.min.js'),
    'node_modules/dayjs/dayjs.min.js'
  ];
  const scripts = runtimes.map(filename => [filename, readFileSync(filename, 'utf8')]);
  const bundle = execFileSync('tar', ['-xOf', archive, source], {
    encoding: 'utf8',
    maxBuffer: 12 * 1024 * 1024
  });
  return [...scripts, [source, bundle]];
}

/** Captures the serializable public catalog in an isolated UMD runtime. */
function captureLocales(scripts) {
  const context = createContext({ setTimeout, clearTimeout, console });
  context.self = context.window = context;
  for (const [filename, script] of scripts) runInContext(script, context, { filename });

  const { locales, version: capturedVersion } = context.antd;
  if (capturedVersion !== version || Object.keys(locales).length !== 73) {
    throw new Error('The pinned UMD locale catalog has changed');
  }
  for (const [code, locale] of Object.entries(locales)) {
    if (!/^[a-z]{2,3}_[A-Z]{2}$/.test(code) || locale.DatePicker !== locale.Calendar) {
      throw new Error(`Unexpected locale structure for ${code}`);
    }
  }

  /** Prevents computed translations from being lost during serialization. */
  function serialize(_key, value) {
    if (typeof value === 'function' || typeof value === 'symbol') {
      throw new Error('Locale catalog contains a non-data field');
    }
    return value;
  }
  return JSON.stringify(locales, serialize);
}

/** Retains the supported rc-picker fields and the shared Calendar and DatePicker rule. */
function publicLocale(locale) {
  const lang = { ...locale.DatePicker.lang };
  delete lang.dayFormat;
  delete lang.dateFormat;
  delete lang.dateTimeFormat;
  const picker = { ...locale.DatePicker, lang };

  return { ...locale, DatePicker: picker, Calendar: picker };
}

/** Writes one module with no shared dependencies on other languages. */
function writeLocale(directory, code, locale) {
  const data = JSON.stringify(locale.DatePicker);
  const fields = Object.entries(locale).map(([key, value]) => {
    const body = ['Calendar', 'DatePicker'].includes(key) ? 'datePicker' : JSON.stringify(value);
    return `  ${key}: ${body}`;
  });
  const header = `// Ant Design ${version} / ${revision}. MIT, ../vendor/LICENSE.ant-design.\n`
    + '// Picker and Pagination: ../vendor/LICENSE.rc-picker, ../vendor/LICENSE.rc-pagination.\n'
    + '// Generated by tools/ant-design-locales.mjs.\n';
  const types = "import type { AntDesignLocale } from '../locale.types';";
  const picker = `const datePicker: AntDesignLocale['DatePicker'] = ${data};`;
  const definition = `const locale: AntDesignLocale = {\n${fields.join(',\n')}\n};`;
  const file = `${header}${types}\n\n${picker}\n\n${definition}\n\nexport default locale;\n`;
  writeFileSync(join(directory, `${code}.ts`), file);
}

const scripts = readScripts();
const first = captureLocales(scripts);
if (first !== captureLocales(scripts)) {
  throw new Error('Repeated locale captures disagree');
}

const directory = 'src/lib/locale';
mkdirSync(directory, { recursive: true });
const digests = {};
for (const [code, captured] of Object.entries(JSON.parse(first))) {
  const locale = publicLocale(captured);
  writeLocale(directory, code, locale);
  digests[code] = checksum(JSON.stringify(locale));
}

const reference = { version, revision, source, archiveSha256, repeated: 2,
  catalogSha256: checksum(first), locales: digests };
const fixtures = 'tests/package/fixtures';
mkdirSync(fixtures, { recursive: true });
writeFileSync(join(fixtures, 'ant-design-locales-reference.json'), JSON.stringify(reference, null, 2) + '\n');
console.log(`Generated ${Object.keys(digests).length} locale modules for Ant Design ${version}`);
